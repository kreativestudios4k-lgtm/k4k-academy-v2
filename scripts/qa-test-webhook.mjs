// One-off test-mode endpoint routing only. Never log protection tokens or signing secrets.
const env=process.env;
if(env.VERCEL_ENV!=='preview'||env.K4K_BILLING_QA_ONLY!=='true'||env.K4K_QA_WEBHOOK_REPOINT!=='true')process.exit(0);
if(!env.STRIPE_SECRET_KEY?.startsWith('sk_test_')||env.K4K_LIVE_PAYMENTS_ENABLED==='true'||!env.VERCEL_URL||!env.K4K_QA_USER_ID)throw Error('QA_WEBHOOK_MODE_NOT_SAFE');
const id='we_1UZJX3L7fmdMaK0kpnrZzeGo';
const api='https://api.stripe.com/v1/webhook_endpoints/'+id;
const headers={Authorization:'Bearer '+env.STRIPE_SECRET_KEY};
const response=await fetch(api,{headers,signal:AbortSignal.timeout(15000)});
if(!response.ok)throw Error('QA_WEBHOOK_READ_'+response.status);
const prior=await response.json();
const url=new URL(prior.url);
if(prior.id!==id||prior.livemode!==false||prior.status!=='enabled'||url.protocol!=='https:'||url.pathname!=='/api/billing/webhook'||!url.hostname.startsWith('kreativestudios4k-site-git-test-k4k-f-4552b5-')||!url.searchParams.has('x-vercel-protection-bypass'))throw Error('QA_WEBHOOK_ORIGINAL_MISMATCH');
const next=new URL('https://'+env.VERCEL_URL+'/api/billing/webhook');
if(!next.hostname.endsWith('-kreative-studios4k.vercel.app'))throw Error('QA_WEBHOOK_TARGET_INVALID');
next.search=url.search;
const update=await fetch(api,{method:'POST',headers:{...headers,'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({url:next.href}).toString(),signal:AbortSignal.timeout(15000)});
if(!update.ok)throw Error('QA_WEBHOOK_UPDATE_'+update.status);
const result=await update.json();
if(result.id!==id||result.livemode!==false||result.url!==next.href||result.status!=='enabled')throw Error('QA_WEBHOOK_UPDATE_MISMATCH');
console.log('K4K QA test-only webhook routed to '+next.origin+next.pathname+'; original signing secret preserved. Academy endpoints unchanged.');
